CREATE TABLE agent_capacity_counters (
    scope_kind varchar NOT NULL,
    scope_id varchar NOT NULL,
    resource_kind varchar NOT NULL,
    capacity_limit bigint NOT NULL,
    reserved bigint NOT NULL DEFAULT 0,
    consumed bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (scope_kind, scope_id, resource_kind),
    CONSTRAINT agent_capacity_counters_nonnegative_check CHECK (capacity_limit >= 0 AND reserved >= 0 AND consumed >= 0),
    CONSTRAINT agent_capacity_counters_limit_check CHECK (reserved + consumed <= capacity_limit)
);

CREATE TABLE agent_capacity_reservations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_kind varchar NOT NULL,
    scope_id varchar NOT NULL,
    resource_kind varchar NOT NULL,
    operation_key varchar NOT NULL,
    allocation_id bigint NOT NULL REFERENCES agent_allocations(id),
    amount bigint NOT NULL,
    state varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at timestamptz,
    CONSTRAINT agent_capacity_reservations_counter_fk
        FOREIGN KEY (scope_kind, scope_id, resource_kind)
        REFERENCES agent_capacity_counters(scope_kind, scope_id, resource_kind),
    CONSTRAINT agent_capacity_reservations_amount_check CHECK (amount > 0),
    CONSTRAINT agent_capacity_reservations_state_check CHECK (state IN ('reserved', 'consumed', 'released')),
    CONSTRAINT agent_capacity_reservations_operation_scope_unique
        UNIQUE (operation_key, scope_kind, scope_id, resource_kind)
);

