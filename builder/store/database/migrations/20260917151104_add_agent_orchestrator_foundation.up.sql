-- Execution leases carry ephemeral concurrency and capacity state. Admissions
-- remain durable execution history; only leases expire or get reconciled.
-- session_id is nullable so allocation cleanup can preserve lease rows after
-- removing allocation sessions.
CREATE TABLE agent_execution_leases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_id bigint NOT NULL REFERENCES agent_execution_admissions(id),
    allocation_id bigint NOT NULL REFERENCES agent_allocations(id),
    session_id bigint REFERENCES agent_allocation_sessions(id),
    heartbeat_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    capacity_hold_until timestamptz,
    ended_at timestamptz,
    end_reason varchar,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT agent_execution_leases_end_reason_check CHECK (end_reason IS NULL OR end_reason IN ('completed', 'failed', 'canceled', 'unknown', 'interrupted'))
);

CREATE UNIQUE INDEX agent_execution_leases_active_session
    ON agent_execution_leases(allocation_id, session_id)
    WHERE ended_at IS NULL;

CREATE INDEX agent_execution_leases_active_allocation_idx
    ON agent_execution_leases(allocation_id)
    WHERE ended_at IS NULL;
