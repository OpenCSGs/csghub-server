CREATE TABLE agent_allocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logical_instance_id bigint NOT NULL REFERENCES agent_instances(id),
    actor_kind varchar NOT NULL,
    actor_id varchar NOT NULL,
    runtime_principal varchar,
    billing_owner varchar,
    resource_key varchar NOT NULL UNIQUE,
    deploy_id bigint REFERENCES deploys(id),
    runtime_generation bigint NOT NULL DEFAULT 0,
    accepted_generation bigint,
    desired_state varchar NOT NULL,
    observed_state varchar NOT NULL,
    operation_sequence bigint NOT NULL DEFAULT 0,
    last_error text,
    idle_expires_at timestamptz,
    absolute_expires_at timestamptz,
    binding_ended_at timestamptz,
    resource_released_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT agent_allocations_actor_kind_check CHECK (actor_kind IN ('user', 'guest')),
    CONSTRAINT agent_allocations_desired_state_check CHECK (desired_state IN ('running', 'suspended', 'released')),
    CONSTRAINT agent_allocations_observed_state_check CHECK (observed_state IN ('pending', 'provisioning', 'ready', 'suspending', 'suspended', 'resuming', 'failed', 'deleting', 'released'))
);

CREATE UNIQUE INDEX agent_allocations_live_actor_logical
    ON agent_allocations(logical_instance_id, actor_kind, actor_id)
    WHERE binding_ended_at IS NULL;

CREATE INDEX agent_allocations_deploy_id_idx
    ON agent_allocations(deploy_id)
    WHERE deploy_id IS NOT NULL;

