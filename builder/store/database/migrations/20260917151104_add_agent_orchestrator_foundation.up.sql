CREATE TABLE agent_execution_admissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    allocation_id bigint NOT NULL REFERENCES agent_allocations(id),
    session_id bigint REFERENCES agent_allocation_sessions(id),
    actor_kind varchar NOT NULL,
    actor_id varchar NOT NULL,
    logical_instance_id bigint NOT NULL REFERENCES agent_instances(id),
    runtime_generation bigint NOT NULL,
    execution_id varchar,
    usage_reservation jsonb NOT NULL DEFAULT '{}'::jsonb,
    status varchar NOT NULL,
    heartbeat_at timestamptz,
    completed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT agent_execution_admissions_actor_kind_check CHECK (actor_kind IN ('user', 'guest')),
    CONSTRAINT agent_execution_admissions_status_check CHECK (status IN ('reserved', 'running', 'unknown', 'completed', 'failed', 'canceled', 'interrupted'))
);

CREATE UNIQUE INDEX agent_execution_admissions_execution_id
    ON agent_execution_admissions(execution_id)
    WHERE execution_id IS NOT NULL;

