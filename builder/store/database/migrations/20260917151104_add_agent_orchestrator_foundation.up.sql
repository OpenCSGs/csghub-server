        FROM agent_instances
        WHERE deleted_at IS NULL AND name IS NOT NULL AND name <> ''
        GROUP BY user_uuid, kind, name
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'cannot add agent instance owner/kind/name uniqueness: duplicate live nonempty names require explicit remediation';
    END IF;
END $$;

