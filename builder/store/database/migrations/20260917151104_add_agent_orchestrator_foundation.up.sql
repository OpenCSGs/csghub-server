ALTER TABLE agent_instances
    ADD COLUMN kind varchar NOT NULL DEFAULT 'runtime',
    ADD COLUMN deletion_started_at timestamptz,
    ADD COLUMN effective_mode varchar,
    ADD COLUMN storage_policy varchar,
    ADD COLUMN blueprint jsonb,
    ADD COLUMN blueprint_sha256 varchar;

ALTER TABLE agent_instances
    ADD CONSTRAINT agent_instances_kind_check
        CHECK (kind IN ('logical', 'runtime')),
    ADD CONSTRAINT agent_instances_mode_check
        CHECK (effective_mode IS NULL OR effective_mode IN ('read_only', 'read_write')),
    ADD CONSTRAINT agent_instances_storage_policy_check
        CHECK (storage_policy IS NULL OR storage_policy IN ('none', 'actor_persistent')),
    ADD CONSTRAINT agent_instances_kind_shape_check CHECK (
        (
            kind = 'logical' AND
            effective_mode IS NOT NULL AND storage_policy IS NOT NULL AND
            blueprint IS NOT NULL AND blueprint_sha256 IS NOT NULL
        ) OR
        (
            kind = 'runtime' AND deletion_started_at IS NULL AND
            blueprint IS NULL AND blueprint_sha256 IS NULL AND
            effective_mode IS NULL AND storage_policy IS NULL
        )
    ),
    ADD CONSTRAINT agent_instances_mode_storage_check CHECK (
        effective_mode IS NULL OR
        (effective_mode = 'read_only' AND storage_policy = 'none') OR
        (effective_mode = 'read_write' AND storage_policy = 'actor_persistent')
    );

