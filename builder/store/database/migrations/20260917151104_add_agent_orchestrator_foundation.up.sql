CREATE TABLE agent_allocation_operations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    allocation_id bigint NOT NULL REFERENCES agent_allocations(id),
    operation_sequence bigint NOT NULL,
    operation_key varchar NOT NULL UNIQUE,
    operation_type varchar NOT NULL,
    status varchar NOT NULL,
    runtime_generation bigint NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    workflow_id varchar,
    dispatch_attempts integer NOT NULL DEFAULT 0,
    dispatch_lease_owner varchar,
    dispatch_lease_expires_at timestamptz,
    dispatched_at timestamptz,
    completed_at timestamptz,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT agent_allocation_operations_type_check CHECK (operation_type IN ('provision', 'suspend', 'resume', 'restart', 'delete', 'detach')),
    CONSTRAINT agent_allocation_operations_status_check CHECK (status IN ('pending', 'dispatching', 'dispatched', 'running', 'completed', 'failed', 'canceled')),
    CONSTRAINT agent_allocation_operations_sequence_unique UNIQUE (allocation_id, operation_sequence)
);

CREATE INDEX agent_allocation_operations_dispatch_idx
    ON agent_allocation_operations(status, dispatch_lease_expires_at, created_at);

