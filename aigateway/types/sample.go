package types

import (
	"context"
	"net/http"
	"time"
)

type SampleKind string

const (
	SampleKindL7API     SampleKind = "l7_api"
	SampleKindInference SampleKind = "inference"
)

// SampleInput contains shared values that protocol-specific sample providers
// use to construct a request.
type SampleInput struct {
	Endpoint string
	Headers  http.Header
	Model    string
	URL      string
	Text     string
	Base64   string
	Other    map[string]any
	// MaxResponseBodyBytes limits the response body returned by Execute. A zero
	// value reads the complete body.
	MaxResponseBodyBytes int64
}

// SampleRequest is an executable HTTP request generated by a sample provider.
type SampleRequest struct {
	Method   string
	Endpoint string
	Headers  http.Header
	Body     []byte
}

// HTTPDoer is the HTTP client boundary used by sample providers.
type HTTPDoer interface {
	Do(*http.Request) (*http.Response, error)
}

// SampleExecutionResult contains a sample request and its execution result.
type SampleExecutionResult struct {
	Request                   *SampleRequest
	StatusCode                int
	Status                    string
	ResponseBody              []byte
	Latency                   time.Duration
	Error                     error
	InferenceFallbackRequired bool
}

// SampleExecutionPolicy defines operational limits for a protocol sample.
type SampleExecutionPolicy struct {
	Timeout    time.Duration
	Multimodal bool
}

// SampleProvider executes protocol-specific samples for health checks and
// connection tests.
type SampleProvider interface {
	Supports(endpoint string) bool
	ExecutionPolicy(kind SampleKind) (SampleExecutionPolicy, error)
	Execute(ctx context.Context, kind SampleKind, input SampleInput, client HTTPDoer) (*SampleExecutionResult, error)
}

// SampleRequestBuilder is implemented by providers that can expose the HTTP
// request used by their default execution path.
type SampleRequestBuilder interface {
	Build(kind SampleKind, input SampleInput) (*SampleRequest, error)
}
